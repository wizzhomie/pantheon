"""The project profile: a small, stable description of a repository.

Deliberately boring, and derived: the profile is regenerated by ``trajan inspect``, not
hand-written. It must not contain absolute paths, timestamps or the current commit, or every
run and every checkout would change it. A diff in the profile has to mean the project changed.
:meth:`ProjectProfile.digest` is what a verification run records to say *which* version of
the project it was checked against.
"""

from __future__ import annotations

import hashlib
import json
from pathlib import Path

from pydantic import Field

from ..contracts.base import StrictModel

PROFILE_VERSION = 1
"""Bumped when the shape changes; runs record the version they were planned against."""

PROFILE_DIR = ".trajan"
PROFILE_NAME = "profile.json"


class ProfileTool(StrictModel):
    """One command the project can run to check itself, and where that claim came from."""

    name: str = Field(
        min_length=1, max_length=40, description="pytest, ruff, mypy, eslint, make-test"
    )
    command: list[str] = Field(
        min_length=1, description="argv, no shell; the engine never shells out"
    )
    source: str = Field(
        min_length=1, max_length=120, description="the file the tool was found in"
    )


class ProjectProfile(StrictModel):
    """Deterministic snapshot of a repository's structure and checks.

    Nothing here is a judgement. Tools are *found*, not chosen: a run decides which of them
    to use, and says why the others were skipped.
    """

    schema_version: int = Field(default=PROFILE_VERSION, description="shape version of this file")
    name: str = Field(min_length=1, max_length=120, description="directory name of the repository")
    languages: dict[str, int] = Field(
        default_factory=dict, description="language -> number of source files"
    )
    package_managers: list[str] = Field(default_factory=list)
    tools: list[ProfileTool] = Field(default_factory=list)
    test_paths: list[str] = Field(default_factory=list)
    entry_points: list[str] = Field(default_factory=list)
    top_level: list[str] = Field(
        default_factory=list, description="directories at the repository root"
    )
    docs: list[str] = Field(default_factory=list, description="documentation files at the root")
    file_count: int = Field(default=0, ge=0, description="files considered, after ignored dirs")
    python_version: str | None = Field(default=None, description="requires-python, when declared")

    def digest(self) -> str:
        """Stable hash of the profile, usable to tie a run to a project state."""
        payload = self.model_dump(mode="json")
        encoded = json.dumps(payload, sort_keys=True, ensure_ascii=False, separators=(",", ":"))
        return hashlib.sha256(encoded.encode("utf-8")).hexdigest()

    def tool(self, name: str) -> ProfileTool | None:
        for tool in self.tools:
            if tool.name == name:
                return tool
        return None

    def summary(self) -> str:
        """One line a human can read without opening the file."""
        stacks = ", ".join(f"{lang} ({count})" for lang, count in sorted(self.languages.items()))
        found = ", ".join(tool.name for tool in self.tools) or "no checks found"
        return f"{self.name}: {stacks or 'no source files'}; tools: {found}"


def profile_path(root: Path) -> Path:
    return Path(root) / PROFILE_DIR / PROFILE_NAME


def write_profile(profile: ProjectProfile, root: Path) -> Path:
    """Write the profile into the project, not into trajan: it belongs to that repository."""
    target = profile_path(root)
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(profile.model_dump_json(indent=2) + "\n", encoding="utf-8")
    return target


def read_profile(root: Path) -> ProjectProfile:
    path = profile_path(root)
    if not path.exists():
        raise FileNotFoundError(
            f"no profile at {path}; run `trajan inspect --repo {root} --write` first"
        )
    return ProjectProfile.model_validate_json(path.read_text(encoding="utf-8"))
