"""Regenerate the committed stub reports for the code-review example.

No model calls, no network, no money: the demo agent replays the planted bugs with three
scripted mistakes. The banner is prepended by this script, so a reader who opens one file
and not the README still knows the numbers are not a measurement of a model.
"""

from __future__ import annotations

import asyncio
from datetime import UTC, datetime

from trajan import EvalReport
from trajan.evals import (
    Dataset,
    compare,
    evaluate,
    render_diff_markdown,
    write_json,
    write_markdown,
)

from .build_dataset import DATASET_PATH
from .demo import build_demo_guarded

SAMPLE_AT = datetime(2026, 11, 23, 2, 0, tzinfo=UTC)
REVISION = "stub"
REPORTS = DATASET_PATH.parents[2] / "reports" / "code_review"

BANNER = """\
> **Stub run — no model calls.** Generated by `make sample` from the demo agent in
> `examples/code_review/demo.py`, which replays the planted bugs with three scripted
> mistakes. This shows how the loop reacts, not how a model performs: the agent model is
> recorded as `demo-stub` on purpose. Real numbers come from a live or replayed model.

"""


async def generate() -> None:
    dataset = Dataset.load(DATASET_PATH)
    guarded = build_demo_guarded()
    baseline = await evaluate(
        guarded.with_mode("baseline"),
        dataset,
        concurrency=1,
        created_at=SAMPLE_AT,
        revision=REVISION,
    )
    report = await evaluate(
        guarded,
        dataset,
        concurrency=1,
        created_at=SAMPLE_AT,
        revision=REVISION,
    )
    _write("sample_baseline", baseline)
    _write("sample_guarded", report)
    diff = compare(baseline, report)
    (REPORTS / "sample_diff.md").write_text(
        BANNER + render_diff_markdown(diff), encoding="utf-8"
    )
    print(f"stub reports -> {REPORTS}")


def _write(stem: str, report: EvalReport) -> None:
    write_json(report, REPORTS / f"{stem}.json")
    markdown = write_markdown(report, REPORTS / f"{stem}.md")
    text = markdown.read_text(encoding="utf-8")
    markdown.write_text(BANNER + text, encoding="utf-8")


if __name__ == "__main__":
    asyncio.run(generate())
