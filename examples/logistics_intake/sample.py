"""Regenerate the committed sample reports. No model calls, no network, no money.

The reports in ``reports/`` are what a visitor opens first, so they are generated by the
same CLI path a project would use — ``evaluate`` and ``compare`` — rather than written by
hand. The only substitution is the agent: :mod:`examples.logistics_intake.demo` replays the
golden answers with scripted defects. Each report carries the label below, so a reader who
opens one file and not the README still knows what it is.
"""

from __future__ import annotations

import asyncio
from datetime import UTC, datetime
from pathlib import Path

from agentqa import EvalReport
from agentqa.evals import (
    Dataset,
    compare,
    evaluate,
    render_diff_markdown,
    write_json,
    write_markdown,
)

from .build_dataset import DATASET_PATH
from .demo import build_demo_guarded

SAMPLE_AT = datetime(2026, 11, 22, 17, 0, tzinfo=UTC)
REVISION = "stub"
REPORTS = Path(__file__).resolve().parents[2] / "reports"

BANNER = """\
> **Stub run — no model calls.** Generated by `make sample` from the demo agent in
> `examples/logistics_intake/demo.py`, which replays each golden answer with one scripted
> defect. This shows how the loop reacts, not how a model performs: the agent model is
> recorded as `demo-stub` on purpose. Real numbers come from a live or replayed model.

"""


async def generate() -> None:
    dataset = Dataset.load(DATASET_PATH)
    guarded = build_demo_guarded()
    baseline = await evaluate(
        guarded.with_mode("baseline"),
        dataset,
        concurrency=1,
        created_at=SAMPLE_AT,
        revision=REVISION,
    )
    report = await evaluate(
        guarded,
        dataset,
        concurrency=1,
        created_at=SAMPLE_AT,
        revision=REVISION,
    )
    _write("sample_baseline", baseline)
    _write("sample_guarded", report)
    diff_path = REPORTS / "sample_diff.md"
    diff_path.write_text(
        BANNER + render_diff_markdown(compare(baseline, report)), encoding="utf-8"
    )
    print(f"stub reports -> {REPORTS}")


def _write(stem: str, report: EvalReport) -> None:
    write_json(report, REPORTS / f"{stem}.json")
    markdown = write_markdown(report, REPORTS / f"{stem}.md")
    text = markdown.read_text(encoding="utf-8")
    markdown.write_text(BANNER + text, encoding="utf-8")


if __name__ == "__main__":
    asyncio.run(generate())
