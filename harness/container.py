"""The box's container: the agent's own vessel, what ``up`` starts, what ``status`` proves.

The image is pinned by digest (``castrum.toml``): a tag can move, a digest cannot, and ADR-010
asks for a pin. The project is mounted **read-only** because the only writer in a box is
Caesar's gate, not the container; the box's ``cella/`` is the only writable mount, and
``tabularium/`` is mounted read-only so the evidence cannot be edited from inside.

The container runs the agent, not a sleep: ``gateway run`` under the image's own supervisor, so
a crash restarts instead of hiding behind a "running" status. ``status`` asks the agent about
itself (``hermes status``) and reports what it answered — a container that is up with a dead
gateway is not "the agent works".

The image refuses ``--user``: it starts as root and remaps the files it writes to
``HERMES_UID``/``HERMES_GID``, so the box's files belong to the host user. The boundary is the
read-only mount, not the process uid — and the model key arrives through the environment, never
through the compose file.

Docker needs the daemon socket, which this user does not have; the module tries plain
``docker`` and falls back to ``sudo -n docker``. Both failing is an error with the reason,
never a silent "started".
"""

from __future__ import annotations

import json
import os
import shlex
import shutil
import subprocess
import time
from dataclasses import dataclass, replace

from . import box as boxes

SERVICE = "augustus"
PROJECT_PREFIX = "pantheon-"
PROJECT_MOUNT = "/work/project"
STATE_MOUNT = "/opt/data"
TABULARIUM_MOUNT = "/work/tabularium"
MEMORY_LIMIT = "1g"
DOCKER_ENV = "PANTHEON_DOCKER"
HERMES = "/opt/hermes/.venv/bin/hermes"
AGENT_MODEL = "deepseek-flash"
AGENT_PROVIDER = "deepseek"
MODEL_KEY_ENV = "DEEPSEEK_API_KEY"
"""How Hermes names the key; ``PANTHEON_MODEL_KEY`` is mapped onto it when ``up`` runs."""
STARTUP_SECONDS = 45


@dataclass(frozen=True, slots=True)
class AgentStatus:
    """What the agent says about itself, read from its own status command."""

    gateway: str | None = None
    model: str | None = None
    provider: str | None = None
    platforms: str | None = None

    @property
    def running(self) -> bool:
        return bool(self.gateway and "running" in self.gateway.lower())

    @property
    def line(self) -> str:
        if not self.running:
            return f"gateway not running ({self.gateway or 'no answer'})"
        bits = []
        if self.model:
            bits.append(f"model {self.model}")
        if self.platforms:
            bits.append(f"platforms {self.platforms}")
        return "gateway up" + (", " + ", ".join(bits) if bits else "")


@dataclass(frozen=True, slots=True)
class Container:
    """What the box's container is doing right now, and what the agent inside says."""

    running: bool
    name: str
    image: str
    detail: str
    agent: AgentStatus | None = None

    @property
    def line(self) -> str:
        if not self.running:
            return f"not running — {self.detail}"
        agent = self.agent.line if self.agent is not None else "not asked"
        return f"running — {self.name} {self.detail}; agent: {agent}"


def project_name(box: boxes.Box) -> str:
    """The compose project: one per box, so two boxes never share a namespace."""
    return PROJECT_PREFIX + box.name


def render_compose(box: boxes.Box, image: str | None = None) -> str:
    """``compose.yaml`` from ``castrum.toml``: one service, the agent, three mounts, one limit."""
    project_mount = _yaml(box.project.as_posix() + ':' + PROJECT_MOUNT + ':ro')
    home_mount = _yaml((box.root / 'cella').as_posix() + ':' + STATE_MOUNT)
    evidence_mount = _yaml(
        (box.root / 'tabularium').as_posix() + ':' + TABULARIUM_MOUNT + ':ro'
    )
    return "\n".join(
        [
            "# Generated by `pantheon up` from castrum.toml. Edit castrum.toml, not this file.",
            "",
            f"name: {_yaml(project_name(box))}",
            "",
            "services:",
            f"  {SERVICE}:",
            f"    image: {_yaml(image or box.image or '')}",
            "    # The agent, supervised by the image's own s6 tree: a crash restarts, it does not",
            "    # hide behind a status that says running.",
            '    command: ["gateway", "run"]',
            "    # Hermes refuses `--user`: it starts as root and remaps what it writes to",
            "    # HERMES_UID/HERMES_GID. The key comes from the caller's environment, never",
            "    # from this file; the boundary is the read-only mount, not the uid.",
            "    environment:",
            f"      - HERMES_UID={os.getuid()}",
            f"      - HERMES_GID={os.getgid()}",
            f"    working_dir: {STATE_MOUNT}",
            "    volumes:",
            f"      - {project_mount}",
            f"      - {home_mount}",
            f"      - {evidence_mount}",
            f"    mem_limit: {MEMORY_LIMIT}",
            '    restart: "no"',
            "",
        ]
    )


def up(box: boxes.Box, image: str | None = None) -> Container:
    """Write the compose file, seed the agent's home, start it, and report what answered."""
    if image is not None:
        box = _with_image(box, boxes.check_image(image))
    if box.image is None:
        raise boxes.HarnessError(
            "the box has no image: `pantheon up --image nousresearch/hermes-agent@sha256:...` "
            "pins one first (a tag can move, a digest cannot)"
        )
    box.compose.write_text(render_compose(box), encoding="utf-8")
    _prepare(box)
    _compose(box, "up", "-d")
    facts = state(box)
    if not facts.running:
        return facts
    if _model_key(box) is None:
        facts = replace(
            facts,
            detail=facts.detail
            + "; no model key: the agent starts, but it cannot call the model",
        )
    return _await_agent(box, facts)


def down(box: boxes.Box) -> Container:
    """Stop and remove the container; the box's files stay where they are."""
    if not box.compose.is_file() or not boxes.compose_services(box.compose):
        return Container(
            False, f"{project_name(box)}-{SERVICE}-1", box.image or "", "nothing to stop"
        )
    _compose(box, "down", "--remove-orphans")
    return state(box)


def state(box: boxes.Box) -> Container:
    """What compose says about the box's container, or why it says nothing."""
    name = f"{project_name(box)}-{SERVICE}-1"
    if not box.compose.is_file():
        return Container(False, name, box.image or "", "no container yet: `pantheon up` starts it")
    try:
        done = _compose(box, "ps", "--all", "--format", "json")
    except boxes.HarnessError as error:
        return Container(False, name, box.image or "", f"cannot be inspected: {error}")
    rows = _parse_ps(done.stdout)
    for item in rows:
        if str(item.get("State", "")).lower() == "running":
            return Container(True, name, box.image or "", f"since {item.get('Status', 'running')}")
    if rows:
        status = str(rows[0].get("Status", "stopped"))
        return Container(False, name, box.image or "", f"stopped: {status}")
    return Container(False, name, box.image or "", "no container yet: `pantheon up` starts it")


def agent_status(box: boxes.Box) -> AgentStatus | None:
    """Ask the agent about itself; ``None`` when there is no container to ask."""
    if not box.compose.is_file():
        return None
    try:
        done = _compose(box, "exec", "-T", SERVICE, HERMES, "status")
    except boxes.HarnessError:
        return None
    return parse_status(done.stdout)


def parse_status(text: str) -> AgentStatus | None:
    """The agent's own summary: four labelled lines, not a guess about the process."""
    fields: dict[str, str] = {}
    for line in text.splitlines():
        if ":" not in line:
            continue
        name, _, value = line.partition(":")
        key = name.strip().lower()
        if key in {"model", "provider", "gateway", "platforms"}:
            fields[key] = value.strip()
    if not fields:
        return None
    return AgentStatus(
        gateway=fields.get("gateway"),
        model=fields.get("model"),
        provider=fields.get("provider"),
        platforms=fields.get("platforms"),
    )


def _prepare(box: boxes.Box) -> None:
    """Give the agent its home once: the box's profile, a model, and the key it needs.

    The key is the box's own secret: it lives in ``cella/.env`` (mode 600, outside git), not in
    the compose file and not in the harness. ``sudo`` strips the caller's environment, so an
    environment passthrough would reach compose and never reach the container.
    """
    home = box.root / "cella"
    home.mkdir(parents=True, exist_ok=True)
    soul = box.root / "persona" / "SOUL.md"
    target = home / "SOUL.md"
    if soul.is_file() and not target.exists():
        target.write_text(soul.read_text(encoding="utf-8"), encoding="utf-8")
    if not (home / "config.yaml").is_file():
        # The image knows its own schema version; asking it is safer than writing the file.
        for key, value in (
            ("model.provider", AGENT_PROVIDER),
            ("model.default", AGENT_MODEL),
        ):
            _compose(
                box,
                "run",
                "--rm",
                "--no-deps",
                "-T",
                # The home belongs to the host user: a root-owned config.yaml makes the
                # agent's own backup of it fail on the first answer (`Permission denied`).
                "-u",
                str(os.getuid()),
                SERVICE,
                HERMES,
                "config",
                "set",
                key,
                value,
            )
    secret = _model_key_from_env()
    if secret is not None:
        _write_secret(box, secret)


def _model_key_from_env() -> str | None:
    return os.environ.get("PANTHEON_MODEL_KEY") or os.environ.get(MODEL_KEY_ENV)


def _model_key(box: boxes.Box) -> str | None:
    """Is there a key the agent could use: in this process, or already in its home?"""
    if _model_key_from_env() is not None:
        return "environment"
    path = box.root / "cella" / ".env"
    try:
        lines = path.read_text(encoding="utf-8").splitlines()
    except OSError:
        return None
    for line in lines:
        if line.startswith(f"{MODEL_KEY_ENV}=") and len(line) > len(MODEL_KEY_ENV) + 1:
            return "cella"
    return None


def _write_secret(box: boxes.Box, key: str) -> None:
    """Keep one key line in the agent's own .env; never in the compose file, never printed."""
    path = box.root / "cella" / ".env"
    try:
        lines = path.read_text(encoding="utf-8").splitlines() if path.is_file() else []
    except OSError:
        lines = []
    kept = [line for line in lines if not line.startswith(f"{MODEL_KEY_ENV}=")]
    kept.append(f"{MODEL_KEY_ENV}={key}")
    path.write_text("\n".join(kept) + "\n", encoding="utf-8")
    path.chmod(0o600)


def _await_agent(box: boxes.Box, facts: Container) -> Container:
    """A container that is up is not yet an agent that answers: wait, then say which it is."""
    deadline = time.monotonic() + STARTUP_SECONDS
    while time.monotonic() < deadline:
        agent = agent_status(box)
        if agent is not None and agent.running:
            return replace(facts, agent=agent)
        time.sleep(1)
    return replace(
        facts,
        detail=facts.detail + f"; the agent did not answer within {STARTUP_SECONDS} s",
    )


def _parse_ps(output: str) -> list[dict[str, object]]:
    """Compose prints a JSON array in v2 and one object per line in some versions."""
    text = output.strip()
    if not text:
        return []
    try:
        data = json.loads(text)
    except json.JSONDecodeError:
        rows = []
        for line in text.splitlines():
            try:
                rows.append(json.loads(line))
            except json.JSONDecodeError:
                continue
        return [row for row in rows if isinstance(row, dict)]
    if isinstance(data, dict):
        return [data]
    return [row for row in data if isinstance(row, dict)]


def _with_image(box: boxes.Box, image: str) -> boxes.Box:
    """Persist a newly pinned image into the box's file, then use that box."""
    updated = boxes.Box(
        root=box.root, name=box.name, project=box.project, created=box.created, image=image
    )
    box.file.write_text(boxes.render_box(updated), encoding="utf-8")
    return updated


def _yaml(value: str) -> str:
    return json.dumps(value)


def _compose(
    box: boxes.Box, *args: str, env: dict[str, str] | None = None
) -> subprocess.CompletedProcess[str]:
    prefix = docker_prefix()
    command = [*prefix, "compose", "-p", project_name(box), "-f", str(box.compose), *args]
    try:
        done = subprocess.run(
            command,
            capture_output=True,
            text=True,
            check=False,
            timeout=300,
            env=env,
        )
    except (OSError, subprocess.SubprocessError) as error:
        raise boxes.HarnessError(f"cannot run docker: {error}") from error
    if done.returncode != 0 and args[0] != "ps":
        detail = (done.stderr or done.stdout).strip().splitlines()
        raise boxes.HarnessError(
            "docker compose "
            + " ".join(args)
            + " failed: "
            + ("; ".join(detail[-4:]) or f"exit {done.returncode}")
        )
    return done


def docker_prefix() -> tuple[str, ...]:
    """The docker command that works here: the override, then plain, then ``sudo -n``."""
    override = os.environ.get(DOCKER_ENV)
    # An explicit override wins or fails: falling back to the real daemon after a broken
    # override would run real containers in a test that asked for none.
    candidates: list[tuple[str, ...]] = (
        [tuple(shlex.split(override))] if override else [("docker",), ("sudo", "-n", "docker")]
    )
    for prefix in candidates:
        if not prefix or shutil.which(prefix[0]) is None:
            continue
        try:
            done = subprocess.run(
                [*prefix, "version", "--format", "{{.Server.Version}}"],
                capture_output=True,
                text=True,
                check=False,
                timeout=20,
            )
        except (OSError, subprocess.SubprocessError):
            continue
        if done.returncode == 0:
            return prefix
    raise boxes.HarnessError(
        "docker is not usable: `${DOCKER_ENV}`, `docker` and `sudo -n docker` cannot reach "
        "the daemon. "
        "The container needs the daemon socket; without it the box and the project still work, "
        "they just have no container."
    )
